/**
 * Scans public/focus/videos|music and generates
 * src/lib/focus-library.generated.ts so dropped-in files appear in the
 * Focus Library with zero config edits.
 *
 * Runs automatically via `predev` / `prebuild`, or manually:
 *   npm run library:sync
 *
 * Conventions:
 * - video: .mp4 .webm .ogv .mov | audio: .mp3 .ogg .oga .wav .m4a
 * - a same-basename image (.jpg/.jpeg/.png/.webp) next to a video
 *   becomes its poster thumbnail.
 * - titles are prettified from filenames; override any entry by adding a
 *   manual record with the same id in src/lib/focus-library.ts.
 */
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname, basename, extname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "public", "focus");
const outFile = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "focus-library.generated.ts");

const VIDEO_EXTS = new Set([".mp4", ".webm", ".ogv", ".mov"]);
const AUDIO_EXTS = new Set([".mp3", ".ogg", ".oga", ".wav", ".m4a"]);
const POSTER_EXTS = new Set([".jpg", ".jpeg", ".png", ".webp"]);

function slug(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "") || "media";
}

function titleize(base) {
  const human = base.replace(/[_-]+/g, " ").replace(/\s+/g, " ").trim();
  if (/^\d+$/.test(human)) return `Ambient ${human}`;
  if (!human) return "Untitled";
  return human.charAt(0).toUpperCase() + human.slice(1);
}

function scan(subdir, exts) {
  const dir = join(root, subdir);
  if (!existsSync(dir)) return [];
  let files = [];
  try {
    files = readdirSync(dir, { withFileTypes: true })
      .filter((e) => e.isFile())
      .map((e) => e.name)
      .sort((a, b) => a.localeCompare(b));
  } catch {
    return [];
  }
  const posters = new Map();
  for (const f of files) {
    const ext = extname(f).toLowerCase();
    if (POSTER_EXTS.has(ext)) posters.set(basename(f, ext).toLowerCase(), f);
  }
  const items = [];
  for (const f of files) {
    const ext = extname(f).toLowerCase();
    if (!exts.has(ext)) continue;
    const base = basename(f, ext);
    const posterFile = posters.get(base.toLowerCase());
    items.push({
      id: slug(base),
      file: f,
      posterFile,
      title: titleize(base),
    });
  }
  return items;
}

const videos = scan("videos", VIDEO_EXTS).map((v) => ({
  id: v.id,
  title: v.title,
  src: `/focus/videos/${encodeURIComponent(v.file)}`,
  ...(v.posterFile ? { poster: `/focus/videos/${encodeURIComponent(v.posterFile)}` } : {}),
}));

const tracks = scan("music", AUDIO_EXTS).map((t) => ({
  id: t.id,
  title: t.title,
  src: `/focus/music/${encodeURIComponent(t.file)}`,
}));

const lines = [
  "// GENERATED by scripts/sync-focus-library.mjs — do not edit by hand.",
  "// Re-run `npm run library:sync` after adding/removing files",
  "// (runs automatically on `npm run dev` and `npm run build`).",
  'import type { FocusVideo, FocusTrack } from "./focus-library";',
  "",
  `export const GENERATED_VIDEOS: FocusVideo[] = ${JSON.stringify(videos, null, 2)};`,
  "",
  `export const GENERATED_TRACKS: FocusTrack[] = ${JSON.stringify(tracks, null, 2)};`,
  "",
];

writeFileSync(outFile, lines.join("\n"));
console.log(`focus-library: ${videos.length} video(s), ${tracks.length} track(s) -> src/lib/focus-library.generated.ts`);
